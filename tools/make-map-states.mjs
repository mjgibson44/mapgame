// Builds map-states.js: the US states and Canada's provinces and territories
// (Natural Earth 50m admin-1), in the same projection as map-data.js, for
// Border Draw's "US states" and "Canada" maps. The District of Columbia is
// folded into Maryland. The admin-1 outlines run out into the lakes, so the
// big lakes come too (Natural Earth 50m lakes), to draw as water.
//
//   npm install d3-geo@3
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_1_states_provinces.geojson
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_lakes.geojson
//   node make-map-states.mjs <dir with the .geojson files> > ../map-states.js
import * as d3 from "d3-geo";
import fs from "fs";

const dir = process.argv[2] || ".";
const read = (f) => JSON.parse(fs.readFileSync(`${dir}/${f}`, "utf8"));
const world110 = read("ne_110m_admin_0_countries.geojson");
const admin1 = read("ne_50m_admin_1_states_provinces.geojson");
const lakes = read("ne_50m_lakes.geojson");

// map-data.js was made with this projection: Natural Earth, fitted to 1000 wide.
const projection = d3.geoNaturalEarth1().fitWidth(1000, world110);

// Projected rings of a feature, cut at the antimeridian like the main map.
function ringsOf(feature) {
  const rings = [];
  let ring;
  d3.geoPath(projection, {
    moveTo(x, y) { ring = [[x, y]]; rings.push(ring); },
    lineTo(x, y) { ring.push([x, y]); },
    closePath() {},
    arc() {},
  })(feature);
  return rings.filter((r) => r.length > 2);
}

// Drops points closer than MIN to the last one kept (the 50m outlines are far
// more detailed than the map needs), rounds to 0.01, and writes an SVG path
// in map-data.js's format: "M x y", then relative "l dx dy", then "Z".
const MIN = 0.06;
const r2 = (v) => Math.round(v * 100) / 100;
function pathOf(rings) {
  let d = "";
  for (const ring of rings) {
    const kept = [ring[0]];
    for (const p of ring.slice(1)) {
      const q = kept[kept.length - 1];
      if (Math.hypot(p[0] - q[0], p[1] - q[1]) >= MIN) kept.push(p);
    }
    if (kept.length < 3) continue;
    const pts = kept.map(([x, y]) => [r2(x), r2(y)]);
    d += `M${pts[0][0]} ${pts[0][1]}`;
    for (let i = 1; i < pts.length; i++) d += `l${r2(pts[i][0] - pts[i - 1][0])} ${r2(pts[i][1] - pts[i - 1][1])}`;
    d += "Z";
  }
  return d;
}

const MERGE = { "US-DC": "US-MD" };
const shapes = {};
const boxes = {};
for (const f of admin1.features) {
  const { iso_a2: country, postal, name } = f.properties;
  if (country !== "US" && country !== "CA") continue;
  const code = MERGE[`${country}-${postal}`] || `${country}-${postal}`;
  const rings = ringsOf(f);
  if (!shapes[code]) shapes[code] = { n: name, rings: [] };
  if (code === `${country}-${postal}`) shapes[code].n = name; // Maryland, not DC
  shapes[code].rings.push(...rings);
  const b = (boxes[country] ||= [Infinity, Infinity, -Infinity, -Infinity]);
  for (const [x, y] of rings.flat()) {
    b[0] = Math.min(b[0], x); b[1] = Math.min(b[1], y);
    b[2] = Math.max(b[2], x); b[3] = Math.max(b[3], y);
  }
}

const out = { boxes: {}, shapes: {} };
for (const [c, [x0, y0, x1, y1]] of Object.entries(boxes)) {
  const m = 4; // a margin round the country
  out.boxes[c] = [r2(x0 - m), r2(y0 - m), r2(x1 - x0 + 2 * m), r2(y1 - y0 + 2 * m)];
}
for (const code of Object.keys(shapes).sort()) out.shapes[code] = { n: shapes[code].n, d: pathOf(shapes[code].rings) };

// The lakes in either map's box big enough to see at its full view (2.5
// square map units and up), as one path. Fill it even-odd: islands in a lake
// are rings too.
const path = d3.geoPath(projection);
const inside = (b, [[x0, y0], [x1, y1]]) => x0 >= b[0] && y0 >= b[1] && x1 <= b[0] + b[2] && y1 <= b[1] + b[3];
out.lakes = pathOf(lakes.features
  .filter((f) => path.area(f) >= 2.5 && Object.values(out.boxes).some((b) => inside(b, path.bounds(f))))
  .flatMap(ringsOf));

process.stdout.write("// Generated by tools/make-map-states.mjs from Natural Earth 50m admin-1 and lakes data.\n");
process.stdout.write(`const MAP_STATES = ${JSON.stringify(out)};\n`);
